-- 전남광주통합특별시 — 광주(24)로 접수된 제보를 전남(36)으로 옮긴다.
--
-- 광주광역시와 전라남도가 통합되면서 지도에서 두 지역을 하나로 합쳤다.
-- 남긴 코드는 전남의 '36' 이다. 지도에서 '24' 가 사라졌으므로, 이미 광주로
-- 들어온 제보가 있다면 옮겨야 지역별 집계(/api/regions)에 잡힌다.
--
--   스키마는 바뀌지 않는다. 이미 들어온 값만 옮긴다.
--   광주로 접수된 제보가 없으면 아무 일도 일어나지 않는다.
--   여러 번 실행해도 결과가 같다.
--
-- 실행:
--   npx wrangler d1 execute dokseong --remote --file=migrations/2026-08-24-gwangju-to-jeonnam.sql

UPDATE reports SET sido = '36' WHERE sido = '24';

